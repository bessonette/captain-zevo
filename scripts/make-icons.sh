#!/bin/sh
# Rebuilds assets/icon.svg and the icon files in assets/icons from
# assets/logo.svg. Run after changing the logo.
# Needs: python3, ImageMagick (magick or convert), and png2icns (icnsutils).
set -eu
cd "$(dirname "$0")/.."

if command -v magick >/dev/null 2>&1; then
    CONVERT=magick
elif command -v convert >/dev/null 2>&1; then
    CONVERT=convert
else
    echo "ImageMagick is required (magick or convert)." >&2
    exit 1
fi
command -v png2icns >/dev/null 2>&1 || { echo "png2icns is required (package icnsutils)." >&2; exit 1; }

# The logo is scaled and centred from its own viewBox, so a replacement logo
# of any size fits. (A nested <svg> would be simpler, but ImageMagick's
# renderer ignores its position.)
python3 - <<'PY'
import re, sys
logo = open("assets/logo.svg").read()
root = re.search(r"<svg\b[^>]*>", logo)
box = root and re.search(r'viewBox="([^"]+)"', root.group(0))
if not box:
    sys.exit("assets/logo.svg needs a root <svg> element with a viewBox")
min_x, min_y, width, height = (float(v) for v in box.group(1).replace(",", " ").split())
scale = 700 / max(width, height)
tx = 512 - (min_x + width / 2) * scale
ty = 512 - (min_y + height / 2) * scale
# Presentation attributes on the logo's root element apply to its contents.
inherited = " ".join(
    f'{name}="{value}"'
    for name, value in re.findall(r'\b(fill|stroke|stroke-width|color)="([^"]*)"', root.group(0))
)
body = re.sub(r"<!--.*?-->", "", logo[root.end():logo.rindex("</svg>")], flags=re.S).strip()
open("assets/icon.svg.tmp", "w").write(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" aria-label="Captain Zevo">
  <!-- App icon: logo.svg on a rounded square sized to the macOS icon grid.
       Generated by scripts/make-icons.sh; edit logo.svg, not this file. -->
  <rect x="100" y="100" width="824" height="824" rx="185" fill="#141f11"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="none" stroke="#2a4a1f" stroke-width="6"/>
  <g transform="translate({tx:.2f} {ty:.2f}) scale({scale:.4f})" {inherited}>
    {body}
  </g>
</svg>
''')
PY

for size in 16 32 128 256 512 1024; do
    "$CONVERT" -background none -density 96 assets/icon.svg.tmp -resize "${size}x${size}" \
        "assets/icons/icon-${size}.png"
done
png2icns assets/icons/icon.icns assets/icons/icon-16.png assets/icons/icon-32.png \
    assets/icons/icon-128.png assets/icons/icon-256.png assets/icons/icon-512.png \
    assets/icons/icon-1024.png >/dev/null
# Windows icon: several sizes in one file.
"$CONVERT" assets/icons/icon-16.png assets/icons/icon-32.png assets/icons/icon-256.png \
    assets/icons/icon.ico
# Only replace the SVG once every raster file was produced.
mv assets/icon.svg.tmp assets/icon.svg
echo "Wrote assets/icon.svg and assets/icons/"
